let currentCategory = "";
let currentQuestionIndex = 0;
let score = 0;

// Функция запуска выбранного теста
function startSelectedQuiz(category) {
    if (!quizDatabase[category]) return;

    currentCategory = category;
    currentQuestionIndex = 0;
    score = 0;

    // Переключение интерфейсов
    document.getElementById("quiz-menu").classList.add("hidden");
    document.getElementById("quiz-body").classList.remove("hidden");

    // Установка заголовка
    document.getElementById("quiz-title-display").innerText =
        quizDatabase[category].title;

    loadQuestion();
}

// Загрузка текущего вопроса
function loadQuestion() {
    const quiz = quizDatabase[currentCategory];
    const qBox = document.getElementById("question-box");
    const rBox = document.getElementById("result-box");

    qBox.classList.remove("hidden");
    rBox.classList.add("hidden");

    const totalQuestions = quiz.questions.length;

    const progressPercent = (currentQuestionIndex / totalQuestions) * 100;
    document.getElementById("progress-fill").style.width =
        `${progressPercent}%`;

    const currentQuestion = quiz.questions[currentQuestionIndex];
    document.getElementById("question").innerText =
        `Вопрос ${currentQuestionIndex + 1} из ${totalQuestions}: ${currentQuestion.q}`;

    const optionsDiv = document.getElementById("options");
    optionsDiv.innerHTML = "";

    currentQuestion.o.forEach((option, index) => {
        const btn = document.createElement("button");
        btn.innerText = option;
        btn.onclick = () => handleAnswer(index);
        optionsDiv.appendChild(btn);
    });
}

// Обработка клика по ответу
function handleAnswer(selectedIndex) {
    const quiz = quizDatabase[currentCategory];
    if (selectedIndex === quiz.questions[currentQuestionIndex].c) {
        score++;
    }

    currentQuestionIndex++;

    if (currentQuestionIndex < quiz.questions.length) {
        loadQuestion();
    } else {
        showResults();
    }
}

// Вывод результатов компиляции теста
function showResults() {
    const quiz = quizDatabase[currentCategory];
    document.getElementById("progress-fill").style.width = "100%";
    document.getElementById("question-box").classList.add("hidden");
    document.getElementById("result-box").classList.remove("hidden");

    let evaluation = "";
    if (score === 10) {
        evaluation =
            "STATUS_OK: Идеальный уровень выживаемости кода и тела. Вы Senior в БЖД!";
    } else if (score >= 7) {
        evaluation =
            "STATUS_WARNING: Хорошо, но система содержит уязвимости. Перечитайте логи.";
    } else {
        evaluation =
            "STATUS_CRITICAL_ERROR: Система разрушена. Высокий риск ЧС на рабочем месте!";
    }

    document.getElementById("result-text").innerHTML = `
        Модуль: <strong>${quiz.title}</strong><br> 
        Успешных тестов: <strong>${score} из 10</strong><br><br> 
        <span style="color: ${score >= 7 ? "#4caf50" : "#f44336"}">${evaluation}</span>
    `;
}

// Кнопка «Пройти заново»
function restartQuiz() {
    currentQuestionIndex = 0;
    score = 0;
    loadQuestion();
}

// Выход обратно в меню выбора категорий
function backToMenu() {
    document.getElementById("quiz-body").classList.add("hidden");
    document.getElementById("quiz-menu").classList.remove("hidden");
}

